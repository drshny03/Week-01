// Creating a class to calculate and display Harry's age
class FindAge {
    public static void main(String[] args) {
        
        // Create a variable for birth year and assign value 2000
        int birthYear = 2000;
        
        // Create a variable for current year and assign value 2024
        int currentYear = 2024;
        
        // Calculate age by subtracting birth year from current year
        int age = currentYear - birthYear;
        
        // Display Harry's age
        System.out.println("Harry's age in " + currentYear + " is " + age);
    }
}
