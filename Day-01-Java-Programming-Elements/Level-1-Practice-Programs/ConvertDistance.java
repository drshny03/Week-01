// Creating a class to convert distance in kilometers to miles
class ConvertDistance {
    public static void main(String[] args) {
        
        // Create a variable for distance in kilometers and assign value 10.8
        double kilometers = 10.8;
        
        // Convert kilometers to miles using the formula: miles = kilometers / 1.6
        double miles = kilometers / 1.6;
        
        // Display the converted distance
        System.out.println("The distance " + kilometers + " km in miles is " + miles);
    }
}
